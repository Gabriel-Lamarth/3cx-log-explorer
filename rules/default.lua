-- Biblioteca padrão de diagnósticos para logs 3CX / VoIP.
-- As regras são heurísticas: valide cada achado com o contexto da chamada.
-- O runtime Lua não recebe acesso a arquivos, processos ou rede.

local function lower(value)
    return string.lower(value or "")
end

local function any(text, needles)
    for _, needle in ipairs(needles) do
        if string.find(text, needle, 1, true) then return true end
    end
    return false
end

local function all(text, needles)
    for _, needle in ipairs(needles) do
        if not string.find(text, needle, 1, true) then return false end
    end
    return true
end

local function rule(id, title, severity, description, recommendation, needles, required)
    return {
        id = id,
        title = title,
        severity = severity,
        description = description,
        recommendation = recommendation,
        match = function(event)
            local text = lower(event.message)
            if not any(text, needles) then return false end
            if required and not all(text, required) then return false end
            return true
        end,
    }
end

